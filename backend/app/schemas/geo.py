def normalize_countries(value: Any) -> list[str]:
    """Alpha-3 codes from what a model wrote: "DEU", "de", "Germany", "EU", or a list of them.
    Unknown names are skipped."""
    raw = value if isinstance(value, list) else [value]
    codes: list[str] = []
    for item in raw:
        if not isinstance(item, str):
            continue
        key = re.sub(r"[\s_.-]+", " ", item).strip().upper()
        key = _ALIASES.get(key, key)
        found = GROUPS.get(key) or (
            (key,) if key in ALPHA3 else (_FROM_ALPHA2[key],) if key in _FROM_ALPHA2 else ()
        )
        codes.extend(c for c in found if c in ALPHA3 and c not in codes)
    return codes
